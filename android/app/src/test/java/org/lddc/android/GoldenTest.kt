/**
 * 与 PC 版上游逐字节比对。golden.json 由 tools/golden/gen_golden.py 用上游代码生成。
 * 归一化：去掉 [tool:...] 行与 ASS 里带版本号的注释行（两端版本号不同）。
 */
class GoldenTest {

    private val formatMap = mapOf(
        "VERBATIMLRC" to LyricsFormat.VERBATIM_LRC,
        "LINEBYLINELRC" to LyricsFormat.LINE_BY_LINE_LRC,
        "ENHANCEDLRC" to LyricsFormat.ENHANCED_LRC,
        "SRT" to LyricsFormat.SRT,
        "ASS" to LyricsFormat.ASS,
    )

    private fun normalize(text: String): String = text.lineSequence()
        .filterNot { it.startsWith("[tool:") || it.contains("Script generated by") }
        .joinToString("\n")
        .trim()

    @Test
    fun `parsers and converters match upstream golden output`() {
        val stream = javaClass.classLoader!!.getResourceAsStream("golden.json")
            ?: error("golden.json 未找到，请先运行 tools/golden/gen_golden.py")
        val root = Json.parseToJsonElement(stream.bufferedReader().readText()).jsonObject
        val cases = root["cases"]!!.jsonArray

        var checked = 0
        for (element in cases) {
            val case = element.jsonObject
            val name = case["name"]!!.jsonPrimitive.content
            val input = case["input"]!!.jsonPrimitive.content
            val sourceName = case["source"]!!.jsonPrimitive.content
            val source = Source.valueOf(sourceName)
            val langs = case["langs"]!!.jsonArray.map { it.jsonPrimitive.content }

            val (tags, data) = LyricsParsers.parse(input, source)
            val lyrics = Lyrics(LyricInfo(source, SongInfo(source, title = "测试歌曲", duration = 30)))
            lyrics.tags.putAll(tags)
            data.forEach { (lang, lines) -> lyrics[lang] = lines }

            val outputs = case["outputs"]!!.jsonObject
            for ((formatName, expectedElement) in outputs) {
                val format = formatMap[formatName] ?: continue
                val expected = normalize(expectedElement.jsonPrimitive.content)
                val actual = normalize(LyricsConverter.convert(lyrics, format, langs))
                assertEquals("case=$name format=$formatName", expected, actual)
                checked++
            }
        }
        assertEquals("应覆盖 5 个样本 × 5 种格式", 25, checked)
    }
}
